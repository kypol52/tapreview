-- TapReview: migration 034 — Telegram Mini App «каталог и отзывы»
--   businesses: catalog_visible (в каталоге только с согласия заведения, по умолчанию выключено),
--               catalog_since, description, city, photos (до 8 картинок из media), категория «barber»;
--   app_users      — пользователи Mini App: только Telegram ID (без имени и username), бан;
--   reviews        — отзыв: 1–5 звёзд, текст, 1 фото, статус pending → published / rejected (сначала проверка),
--                    card_id — отзыв оставлен по ссылке с карты TapReview (подписанный билет, см. src/app-auth.js),
--                    ответ заведения; один отзыв от пользователя на заведение (можно изменить — снова на проверку);
--   review_reports — жалобы на отзывы;
--   favorites      — избранные заведения;
--   app_catalog()  — каталог с поиском, фильтрами и рейтингом (только опубликованные отзывы).
-- Run on the server: sudo -u postgres psql -d tapreview -f /opt/tapreview/site/supabase/migrations/034_miniapp.sql
--   then: sudo systemctl restart postgrest
-- Safe to run several times. Existing data is not changed (only new columns with defaults).

begin;

-- 1. Заведения: поля каталога
alter table public.businesses
  add column if not exists catalog_visible boolean not null default false,
  add column if not exists catalog_since timestamptz,
  add column if not exists description text check (char_length(description) <= 1000),
  add column if not exists city text check (char_length(city) <= 60),
  add column if not exists photos uuid[] not null default '{}' check (cardinality(photos) <= 8);

alter table public.businesses
  drop constraint if exists businesses_category_values;
alter table public.businesses
  add constraint businesses_category_values
  check (category in ('restaurant', 'beauty', 'barber', 'shop', 'hotel', 'auto', 'other'));

-- Дата появления в каталоге (для «Недавно добавленные») ставится сама при включении catalog_visible
create or replace function public.set_catalog_since()
returns trigger
language plpgsql
set search_path = ''
as $fn$
begin
  if new.catalog_visible and new.catalog_since is null then
    new.catalog_since = now();
  end if;
  return new;
end;
$fn$;

drop trigger if exists businesses_set_catalog_since on public.businesses;
create trigger businesses_set_catalog_since
  before insert or update on public.businesses
  for each row
  execute function public.set_catalog_since();

-- 2. Картинки: фото отзывов и фото заведения для каталога
alter table public.media
  drop constraint if exists media_kind_check;
alter table public.media
  add constraint media_kind_check check (kind in ('bg', 'logo', 'moment', 'review', 'place'));

-- 3. Пользователи Mini App
create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  tg_id bigint not null unique,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  banned_at timestamptz,
  ban_reason text check (char_length(ban_reason) <= 200)
);

-- 4. Отзывы
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses (id) on delete cascade,
  user_id bigint not null references public.app_users (id) on delete cascade,
  score smallint not null check (score between 1 and 5),
  text text not null default '' check (char_length(text) <= 2000),
  photo_id uuid references public.media (id) on delete set null,
  status text not null default 'pending' check (status in ('pending', 'published', 'rejected')),
  reject_reason text check (char_length(reject_reason) <= 200),
  card_id bigint references public.cards (id) on delete set null,
  reply_text text check (char_length(reply_text) <= 1000),
  reply_at timestamptz,
  moderated_at timestamptz,
  edited_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (business_id, user_id)
);
create index if not exists reviews_business_status_idx on public.reviews (business_id, status, created_at desc);
create index if not exists reviews_status_idx on public.reviews (status, updated_at);
create index if not exists reviews_user_idx on public.reviews (user_id, updated_at desc);

drop trigger if exists reviews_set_updated_at on public.reviews;
create trigger reviews_set_updated_at
  before update on public.reviews
  for each row
  execute function public.set_updated_at();

-- 5. Жалобы
create table if not exists public.review_reports (
  id bigint generated by default as identity primary key,
  review_id bigint not null references public.reviews (id) on delete cascade,
  user_id bigint not null references public.app_users (id) on delete cascade,
  reason text not null check (reason in ('spam', 'offensive', 'fake', 'personal', 'other')),
  comment text check (char_length(comment) <= 500),
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  unique (review_id, user_id)
);
create index if not exists review_reports_open_idx on public.review_reports (created_at) where resolved_at is null;

-- 6. Избранное
create table if not exists public.favorites (
  user_id bigint not null references public.app_users (id) on delete cascade,
  business_id bigint not null references public.businesses (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, business_id)
);

-- 7. Каталог: заведения с согласием + рейтинг по опубликованным отзывам + просмотры за 30 дней
create or replace function public.app_catalog(
  p_q text default null,
  p_category text default null,
  p_min_score numeric default null,
  p_min_reviews integer default 0,
  p_sort text default 'top',
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id bigint,
  slug text,
  name text,
  category text,
  city text,
  address text,
  tagline text,
  logo_url text,
  design jsonb,
  cover uuid,
  reviews bigint,
  avg_score numeric,
  views_30d bigint,
  catalog_since timestamptz
)
language sql
stable
set search_path = ''
as $fn$
  with base as (
    select
      b.id, b.slug, b.name, b.category, b.city, b.address, b.tagline, b.logo_url, b.design,
      b.photos[1] as cover,
      coalesce(r.cnt, 0) as reviews,
      r.avg as avg_score,
      coalesce(v.cnt, 0) as views_30d,
      coalesce(b.catalog_since, b.created_at) as catalog_since
    from public.businesses b
    left join lateral (
      select count(*) as cnt, round(avg(x.score)::numeric, 1) as avg
      from public.reviews x
      where x.business_id = b.id and x.status = 'published'
    ) r on true
    left join lateral (
      select count(*) as cnt
      from public.click_events e
      where e.business_id = b.id and e.event_type = 'page_view' and e.created_at >= now() - interval '30 days'
    ) v on true
    where b.is_active and b.catalog_visible
      and (p_category is null or b.category = p_category
           or (p_category = 'other' and b.category not in ('restaurant', 'beauty', 'barber', 'shop')))
      and (p_q is null or p_q = ''
           or strpos(lower(b.name), lower(p_q)) > 0
           or strpos(lower(coalesce(b.address, '')), lower(p_q)) > 0
           or strpos(lower(coalesce(b.city, '')), lower(p_q)) > 0
           or strpos(lower(coalesce(b.tagline, '')), lower(p_q)) > 0)
  )
  select * from base
  where (p_min_score is null or base.avg_score >= p_min_score)
    and base.reviews >= greatest(coalesce(p_min_reviews, 0), 0)
  order by
    case when p_sort = 'top' then base.avg_score end desc nulls last,
    case when p_sort = 'top' then base.reviews end desc,
    case when p_sort = 'popular' then base.views_30d end desc,
    case when p_sort = 'new' then base.catalog_since end desc,
    base.name asc
  limit least(greatest(coalesce(p_limit, 20), 1), 50)
  offset greatest(coalesce(p_offset, 0), 0);
$fn$;

-- 8. Рейтинг одного заведения: распределение звёзд по опубликованным отзывам
create or replace function public.app_place_rating(p_business_id bigint)
returns table (score smallint, cnt bigint)
language sql
stable
set search_path = ''
as $fn$
  select x.score, count(*)
  from public.reviews x
  where x.business_id = p_business_id and x.status = 'published'
  group by x.score;
$fn$;

-- 9. Доступ: только сервер (service_role), браузер напрямую в базу не ходит
alter table public.app_users enable row level security;
alter table public.reviews enable row level security;
alter table public.review_reports enable row level security;
alter table public.favorites enable row level security;
revoke all on public.app_users, public.reviews, public.review_reports, public.favorites from anon, authenticated;
grant select, insert, update, delete
  on public.app_users, public.reviews, public.review_reports, public.favorites to service_role;
grant usage, select on all sequences in schema public to service_role;

revoke all on function public.app_catalog(text, text, numeric, integer, text, integer, integer) from public, anon, authenticated;
grant execute on function public.app_catalog(text, text, numeric, integer, text, integer, integer) to service_role;
revoke all on function public.app_place_rating(bigint) from public, anon, authenticated;
grant execute on function public.app_place_rating(bigint) to service_role;

commit;
