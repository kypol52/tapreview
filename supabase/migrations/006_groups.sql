-- TapReview: migration 006 (groups)
-- A group = one QR / NFC link that opens a page with a list of venues.
-- Each venue in the list leads to its usual page /b/:slug.
-- Existing businesses and their links are not changed.
-- Safe to run several times.

begin;

create table if not exists public.business_groups (
  id bigint generated by default as identity primary key,
  slug text not null,
  name text not null,
  tagline text,
  logo_url text,
  -- venues in display order (ids from public.businesses)
  business_ids bigint[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists business_groups_slug_key
  on public.business_groups (slug);

alter table public.business_groups
  drop constraint if exists business_groups_checks;
alter table public.business_groups
  add constraint business_groups_checks check (
    slug ~ '^[A-Za-z0-9_-]{3,64}$'
    and char_length(name) between 1 and 200
    and char_length(coalesce(tagline, '')) <= 80
    and coalesce(logo_url, 'https://') like 'https://%'
    and cardinality(business_ids) <= 50
  );

drop trigger if exists business_groups_set_updated_at
  on public.business_groups;
create trigger business_groups_set_updated_at
  before update on public.business_groups
  for each row
  execute function public.set_updated_at();

-- No browser access: only the server (secret key) reads and writes groups
alter table public.business_groups enable row level security;
revoke all on public.business_groups from anon, authenticated;

grant select, insert, update, delete
  on public.business_groups to service_role;
grant usage, select
  on all sequences in schema public to service_role;

commit;
