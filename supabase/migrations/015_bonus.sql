-- TapReview: migration 015 (guest bonus: one-time codes, prize wheel)
-- The bonus is NOT tied to reviews (platform rules): every guest who scanned the card can get it.
-- 1) businesses: bonus settings
--      bonus_mode       off | fixed (one prize = discount_text) | wheel (bonus_prizes)
--      bonus_prizes     [{"label": "Кофе в подарок", "weight": 15}, ...] — 2..8 prizes, weight = chance
--      bonus_from_days  code starts working N days later (1 = from tomorrow, 0 = right away)
--      bonus_valid_days how long the code works after that
--      bonus_cooldown_days  one bonus per device per N days
--      bonus_conditions text shown to the guest and to the cashier ("от 500 ₽, один код на чек")
-- 2) bonus_codes: issued codes; the cashier redeems them on the owner's stats link (/s/TOKEN/bonus)
-- No personal data: visitor_key is a salted hash of a random device id from a cookie.
-- Safe to run several times.

begin;

alter table public.businesses
  add column if not exists bonus_mode text not null default 'off',
  add column if not exists bonus_prizes jsonb not null default '[]'::jsonb,
  add column if not exists bonus_from_days integer not null default 1,
  add column if not exists bonus_valid_days integer not null default 14,
  add column if not exists bonus_cooldown_days integer not null default 30,
  add column if not exists bonus_conditions text;

alter table public.businesses
  drop constraint if exists businesses_bonus_checks;
alter table public.businesses
  add constraint businesses_bonus_checks check (
    bonus_mode in ('off', 'fixed', 'wheel')
    and jsonb_typeof(bonus_prizes) = 'array'
    and jsonb_array_length(bonus_prizes) <= 8
    and bonus_from_days between 0 and 30
    and bonus_valid_days between 1 and 365
    and bonus_cooldown_days between 1 and 365
    and char_length(coalesce(bonus_conditions, '')) <= 200
  );

-- The old "code word" button keeps working as a fixed bonus
update public.businesses
  set bonus_mode = 'fixed'
  where bonus_mode = 'off' and coalesce(discount_code, '') <> '';

create table if not exists public.bonus_codes (
  id bigint generated by default as identity primary key,
  code text not null,
  business_id bigint not null references public.businesses (id) on delete cascade,
  card_id bigint references public.cards (id) on delete set null,
  prize text not null,
  conditions text,
  visitor_key text not null,
  created_at timestamptz not null default now(),
  valid_from timestamptz not null,
  valid_until timestamptz not null,
  redeemed_at timestamptz
);

create unique index if not exists bonus_codes_code_key on public.bonus_codes (code);
create index if not exists bonus_codes_visitor_idx on public.bonus_codes (business_id, visitor_key, created_at desc);
create index if not exists bonus_codes_business_idx on public.bonus_codes (business_id, created_at desc);

alter table public.bonus_codes
  drop constraint if exists bonus_codes_checks;
alter table public.bonus_codes
  add constraint bonus_codes_checks check (
    code ~ '^[A-Z0-9]{6}$'
    and char_length(prize) between 1 and 60
    and char_length(coalesce(conditions, '')) <= 200
    and valid_until > valid_from
  );

alter table public.bonus_codes enable row level security;
revoke all on public.bonus_codes from anon, authenticated;
grant select, insert, update, delete on public.bonus_codes to service_role;
grant usage, select on all sequences in schema public to service_role;

commit;
