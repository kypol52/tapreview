-- TapReview: migration 009 (Telegram bot for business owners)
-- 1) tg_invites: one-time links that connect a Telegram chat to a business
-- 2) tg_subscribers: which chats receive statistics of which business
-- 3) business_report: totals of several businesses for two time windows (current / previous)
-- Safe to run several times.

begin;

-- 1. One-time invite links (t.me/<bot>?start=CODE), valid for 7 days
create table if not exists public.tg_invites (
  code text primary key,
  business_id bigint not null
    references public.businesses (id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '7 days',
  used_at timestamptz,
  used_by_chat bigint
);

alter table public.tg_invites
  drop constraint if exists tg_invites_checks;
alter table public.tg_invites
  add constraint tg_invites_checks check (code ~ '^[A-Za-z0-9]{16,32}$');

create index if not exists tg_invites_business_idx
  on public.tg_invites (business_id);

-- 2. Connected chats (one chat can follow several businesses, one business — several chats)
create table if not exists public.tg_subscribers (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  business_id bigint not null
    references public.businesses (id) on delete cascade,
  chat_title text,
  weekly_report boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists tg_subscribers_chat_business_key
  on public.tg_subscribers (chat_id, business_id);
create index if not exists tg_subscribers_business_idx
  on public.tg_subscribers (business_id);

-- 3. Report: events of the given businesses in the current window [p_from, p_to)
--    and in the previous window [p_prev_from, p_prev_to), for comparison
create or replace function public.business_report(
  p_business_ids bigint[],
  p_from timestamptz,
  p_to timestamptz,
  p_prev_from timestamptz,
  p_prev_to timestamptz
)
returns table (
  business_id bigint,
  is_current boolean,
  event_type text,
  destination text,
  source text,
  card_id bigint,
  events bigint
)
language sql
stable
set search_path = ''
as $fn$
  select
    e.business_id,
    e.created_at >= p_from,
    e.event_type,
    e.destination,
    e.source,
    e.card_id,
    count(*)
  from public.click_events e
  where e.business_id = any (p_business_ids)
    and (
      (e.created_at >= p_from and e.created_at < p_to)
      or (e.created_at >= p_prev_from and e.created_at < p_prev_to)
    )
  group by 1, 2, 3, 4, 5, 6;
$fn$;

revoke all on function public.business_report(bigint[], timestamptz, timestamptz, timestamptz, timestamptz)
  from public, anon, authenticated;
grant execute on function public.business_report(bigint[], timestamptz, timestamptz, timestamptz, timestamptz)
  to service_role;

-- 4. No browser access: only the server (secret key)
alter table public.tg_invites enable row level security;
alter table public.tg_subscribers enable row level security;
revoke all on public.tg_invites from anon, authenticated;
revoke all on public.tg_subscribers from anon, authenticated;

grant select, insert, update, delete
  on public.tg_invites, public.tg_subscribers to service_role;
grant usage, select
  on all sequences in schema public to service_role;

commit;
