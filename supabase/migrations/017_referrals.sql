-- TapReview: migration 017 (referrals: "card as advertising" + "bring a friend — a month free for both")
-- Every business has a referral link tapreview.ru/r/SLUG (slug is already unique and public).
--   ?s=card — from the "Хочу такую карту" link on its review page (guests who are business owners)
--   ?s=link — the owner shared the link (stats page: Telegram / WhatsApp buttons)
-- 1) businesses.referred_by  — who brought this business (set in the admin panel)
--    businesses.ref_reward_at — when the "month free for both" reward was given for this business
-- 2) ref_visits — visits by referral links (no personal data: business, source, time)
-- Safe to run several times.

begin;

alter table public.businesses
  add column if not exists referred_by bigint references public.businesses (id) on delete set null,
  add column if not exists ref_reward_at timestamptz;

alter table public.businesses
  drop constraint if exists businesses_ref_not_self;
alter table public.businesses
  add constraint businesses_ref_not_self check (referred_by is null or referred_by <> id);

create index if not exists businesses_referred_by_idx on public.businesses (referred_by);

create table if not exists public.ref_visits (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses (id) on delete cascade,
  source text not null,
  created_at timestamptz not null default now()
);

alter table public.ref_visits
  drop constraint if exists ref_visits_checks;
alter table public.ref_visits
  add constraint ref_visits_checks check (source in ('card', 'link'));

create index if not exists ref_visits_business_idx on public.ref_visits (business_id, created_at desc);

alter table public.ref_visits enable row level security;
revoke all on public.ref_visits from anon, authenticated;
grant select, insert, update, delete on public.ref_visits to service_role;
grant usage, select on all sequences in schema public to service_role;

commit;
