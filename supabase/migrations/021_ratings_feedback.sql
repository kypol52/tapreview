-- TapReview: migration 021 (rating first, then reviews; private feedback for low scores)
-- Guest page: venue card → "How was it?" 1–5 →
--   4–5: review platform buttons;  1–3: private message to the owner (+ a small link to the platforms — available to everyone).
-- Gift (wheel) is shown after any score, the same for everyone.
--   businesses.rating_first — turn the rating step on/off per venue (on by default)
--   ratings  — one row per visitor per 30 min (changing the score within that window updates it)
--   feedback — the guest's text for scores 1–3 (no name/phone fields)
-- Run on the server: sudo -u postgres psql -d tapreview < /opt/tapreview/site/supabase/migrations/021_ratings_feedback.sql
--   then: sudo systemctl restart postgrest
-- Safe to run several times.

begin;

alter table public.businesses
  add column if not exists rating_first boolean not null default true;

create table if not exists public.ratings (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses (id) on delete cascade,
  card_id bigint references public.cards (id) on delete set null,
  score smallint not null check (score between 1 and 5),
  source text not null default 'direct' check (source in ('nfc', 'qr', 'direct')),
  dedupe_key text not null unique,
  created_at timestamptz not null default now()
);
create index if not exists ratings_business_created_idx on public.ratings (business_id, created_at);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  business_id bigint not null references public.businesses (id) on delete cascade,
  card_id bigint references public.cards (id) on delete set null,
  score smallint not null check (score between 1 and 5),
  text text not null check (char_length(text) between 1 and 1000),
  source text not null default 'direct' check (source in ('nfc', 'qr', 'direct')),
  visitor_hash text not null,
  tg_delivered boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists feedback_business_created_idx on public.feedback (business_id, created_at desc);

alter table public.ratings enable row level security;
alter table public.feedback enable row level security;
grant select, insert, update, delete on public.ratings, public.feedback to service_role;
grant usage, select on all sequences in schema public to service_role;

commit;
