-- TapReview: migration 008 (cards)
-- Template cards: every printed card has its own code and QR (tapreview.ru/c/CODE).
-- A card is assigned to a business in the admin panel and can be reassigned
-- at any time without reprinting. Existing /b/ links keep working as before.
-- Safe to run several times.

begin;

-- 1. Cards
create table if not exists public.cards (
  id bigint generated by default as identity primary key,
  code text not null,
  business_id bigint
    references public.businesses (id) on delete set null,
  label text,
  is_active boolean not null default true,
  assigned_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists cards_code_key
  on public.cards (code);
create index if not exists cards_business_idx
  on public.cards (business_id);

alter table public.cards
  drop constraint if exists cards_checks;
alter table public.cards
  add constraint cards_checks check (
    code ~ '^[A-Z0-9]{4,12}$'
    and char_length(coalesce(label, '')) <= 60
  );

drop trigger if exists cards_set_updated_at
  on public.cards;
create trigger cards_set_updated_at
  before update on public.cards
  for each row
  execute function public.set_updated_at();

-- 2. Statistics: which card the visitor came from
alter table public.click_events
  add column if not exists card_id bigint
    references public.cards (id) on delete set null;

create index if not exists click_events_card_created_idx
  on public.click_events (card_id, created_at desc)
  where card_id is not null;

-- 3. Totals per card (for the admin panel)
create or replace function public.card_stats_summary(
  p_days integer default 30
)
returns table (
  card_id bigint,
  page_views bigint,
  clicks bigint
)
language sql
stable
set search_path = ''
as $fn$
  select
    e.card_id,
    count(*) filter (where e.event_type = 'page_view'),
    count(*) filter (where e.event_type = 'click')
  from public.click_events e
  where e.card_id is not null
    and e.created_at >= now()
      - make_interval(days => greatest(1, least(p_days, 365)))
  group by e.card_id;
$fn$;

revoke all on function public.card_stats_summary(integer)
  from public, anon, authenticated;
grant execute on function public.card_stats_summary(integer)
  to service_role;

-- 4. No browser access: only the server (secret key)
alter table public.cards enable row level security;
revoke all on public.cards from anon, authenticated;

grant select, insert, update, delete
  on public.cards to service_role;
grant usage, select
  on all sequences in schema public to service_role;

