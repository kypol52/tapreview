-- TapReview: migration 013 (orders from the website)
-- 1) orders            — requests from tapreview.ru/order/ (calculator + contact form)
-- 2) order_recipients  — Telegram chats that receive new orders (connected from the admin panel)
-- 3) order_invites     — one-time links that connect a chat to order notifications (valid 1 day)
-- Personal data: only what the form asks for. No IP addresses are stored.
-- Safe to run several times.

begin;

-- 1. Orders
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  status text not null default 'new',
  name text not null,
  phone text,
  telegram text,
  business_name text not null,
  city text,
  comment text,
  venues integer not null,
  cards integer not null,
  plan text not null,
  total_now integer not null,
  total_next integer not null,
  consent_at timestamptz not null,
  consent_version text not null,
  tg_delivered boolean not null default false
);

alter table public.orders
  drop constraint if exists orders_checks;
alter table public.orders
  add constraint orders_checks check (
    status in ('new', 'in_work', 'done', 'rejected')
    and plan in ('month', 'year')
    and venues between 1 and 50
    and cards between 1 and 500
    and cards >= venues
    and char_length(name) between 1 and 80
    and char_length(coalesce(phone, '')) <= 30
    and char_length(coalesce(telegram, '')) <= 40
    and (coalesce(phone, '') <> '' or coalesce(telegram, '') <> '')
    and char_length(business_name) between 1 and 120
    and char_length(coalesce(city, '')) <= 80
    and char_length(coalesce(comment, '')) <= 1000
    and char_length(consent_version) <= 40
  );

create index if not exists orders_created_idx
  on public.orders (created_at desc);

-- 2. Who gets new orders in Telegram
create table if not exists public.order_recipients (
  chat_id bigint primary key,
  chat_title text,
  created_at timestamptz not null default now()
);

-- 3. One-time links t.me/<bot>?start=CODE
create table if not exists public.order_invites (
  code text primary key,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '1 day',
  used_at timestamptz
);

alter table public.order_invites
  drop constraint if exists order_invites_checks;
alter table public.order_invites
  add constraint order_invites_checks check (code ~ '^[A-Za-z0-9]{16,32}$');

-- 4. No browser access: only the server (secret key)
alter table public.orders enable row level security;
alter table public.order_recipients enable row level security;
alter table public.order_invites enable row level security;
revoke all on public.orders, public.order_recipients, public.order_invites from anon, authenticated;

grant select, insert, update, delete
  on public.orders, public.order_recipients, public.order_invites to service_role;
grant usage, select
  on all sequences in schema public to service_role;

commit;
